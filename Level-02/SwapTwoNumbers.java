public class SwapTwoNumbers {
    public static void main(String[] args) {
        int number1 = 5;
        int number2 = 10;

		// swapped the two numbers 
        int temp = number1;
        number1 = number2;
        number2 = temp;
			// print the result
        System.out.println("The swapped numbers are = " + number1 + "  and  " + number2);


    }
}
